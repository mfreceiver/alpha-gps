def _comp(base, tint, a):
    return L.blend(base, tint, a)


def contrast_rows():
    """WCAG contrast of text on glass, computed against the worst-case composite backdrop."""
    rows = []
    lt, dk = L.LIGHT, L.DARK
    # light G1 over the most saturated backdrop blob
    worst_l = L.blend(lt["bg"], lt["blob1"], 0.60)
    g1l = _comp(worst_l, "#FFFFFF", 0.58)
    g3l = _comp(worst_l, "#FFFFFF", 0.86)
    worst_d = L.blend(dk["bg"], dk["blob1"], 0.42)
    g1d = _comp(worst_d, "#FFFFFF", 0.07)
    g3d = _comp(worst_d, "#272C33", 0.86)
    gv_black = _comp("#000000", "#101418", 0.66)
    gv_white = _comp("#FFFFFF", "#101418", 0.66)
    tag_white = _comp("#FFFFFF", "#000000", 0.60)
    cases = [
        ("亮 · G1 卡片 · 正文 onSurface", lt["onSurf"], g1l, 4.5), ("亮 · G1 卡片 · 次要 onSurfaceVariant", lt["onSurfV"], g1l, 4.5),
        ("亮 · G1 卡片 · 主色文字/图标", lt["primary"], g1l, 4.5), ("亮 · G1 卡片 · 绿色状态字", lt["green"], g1l, 4.5),
        ("亮 · G3 对话框 · 错误色文字", lt["error"], g3l, 4.5),
        ("暗 · G1 卡片 · 正文", dk["onSurf"], g1d, 4.5), ("暗 · G1 卡片 · 次要", dk["onSurfV"], g1d, 4.5),
        ("暗 · G1 卡片 · 主色", dk["primary"], g1d, 4.5), ("暗 · G3 对话框 · 错误色", dk["error"], g3d, 4.5),
        ("主按钮 · 亮（白字 / #0B57D0）", "#FFFFFF", lt["primary"], 4.5), ("主按钮 · 暗（#062E6F / #A8C7FA）", dk["onPrimary"], dk["primary"], 4.5),
        ("预览 GV · 白字（底为黑）", "#FFFFFF", gv_black, 4.5), ("预览 GV · 次要 #C4C9D1（底为黑）", "#C4C9D1", gv_black, 4.5),
        ("预览 GV · 白字（压在纯白照片上，最坏）", "#FFFFFF", gv_white, 4.5),
        ("信息 tag · 白字（压在纯白照片上，最坏）", "#FFFFFF", tag_white, 4.5),
    ]
    for lab, fg, bg, need in cases:
        c = L.contrast(fg, bg)
        ok = '<span class="ok">AA ✓</span>' if c >= need else '<span class="todo">不足</span>'
        rows.append([lab, f'<span class="sw" style="width:30px;height:16px;background:{bg}"></span> <code>{bg}</code>',
                     f'<code>{fg}</code>', f"{c:.1f} : 1", ok])
    return rows


