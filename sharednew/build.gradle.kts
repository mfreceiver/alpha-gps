// Generates SupportedLanguages.kt from the Weblate-managed locale folders in
// composeResources, so merging a translation PR is the only step needed to
// register a new language (picker entries, tags and native display names).
val supportedLanguagesDir = layout.buildDirectory.dir("generated/supportedLanguages/kotlin")
val generateSupportedLanguages = tasks.register("generateSupportedLanguages") {
    val resDir = layout.projectDirectory.dir("src/commonMain/composeResources").asFile
    val localeFolders = providers.provider {
        resDir.listFiles { file: File -> file.isDirectory }.orEmpty()
            .map { it.name }
            .filter { it == "values" || it.startsWith("values-") }
            .sorted()
    }
    inputs.property("localeFolders", localeFolders)
    outputs.dir(supportedLanguagesDir)
    doLast {
        // Android resource qualifier -> BCP-47 tag; the bare "values" folder is
        // the development language, English.
        fun folderToTag(folder: String): String? {
            if (folder == "values") return "en"
            val qualifier = folder.removePrefix("values-")
            if (qualifier.startsWith("b+")) return qualifier.removePrefix("b+").replace('+', '-')
            val parts = qualifier.split("-r", limit = 2)
            val language = when (val lang = parts[0]) {
                // Android resource folders use the legacy ISO codes; BCP-47 doesn't.
                "in" -> "id"
                "iw" -> "he"
                "ji" -> "yi"
                else -> lang
            }
            // Skip non-locale qualifiers (theme, density, ...)
            if (!language.matches(Regex("[a-z]{2,3}"))) return null
            return if (parts.size == 2) "$language-${parts[1]}" else language
        }

        // The language's own name for itself, from the JDK's CLDR data.
        fun displayName(tag: String): String {
            val locale = Locale.forLanguageTag(tag)
            val name = locale.getDisplayLanguage(locale).ifBlank { tag }
            return name.replaceFirstChar { if (it.isLowerCase()) it.titlecase(locale) else it.toString() }
        }

        val tags = localeFolders.get().mapNotNull(::folderToTag).distinct()
            .sortedWith(compareBy({ it != "en" }, { it }))
        val entries = tags.joinToString("\n") { tag ->
            "        AppLanguage(tag = \"$tag\", displayName = \"${displayName(tag)}\"),"
        }
        val file = supportedLanguagesDir.get()
            .file("com/sasch/cameragps/sharednew/language/SupportedLanguages.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// GENERATED by :sharednew:generateSupportedLanguages — do not edit.
            |// Derived from the src/commonMain/composeResources/values-* folders, so a
            |// merged Weblate language lands here (and in the in-app picker) automatically.
            |package com.sasch.cameragps.sharednew.language
            |
            |object SupportedLanguages {
            |    val entries: List<AppLanguage> = listOf(
            |$entries
            |    )
            |
            |    fun fromTag(tag: String): AppLanguage? {
            |        val normalized = tag.substringBefore('-').lowercase()
            |        return entries.firstOrNull { it.tag.substringBefore('-').lowercase() == normalized }
            |    }
            |}
            |""".trimMargin()
        )
    }
}


val heifTestFixturesDir = layout.buildDirectory.dir("generated/heifTestFixtures/kotlin")
// Opt-in originals stay outside the repository and are packaged only in the test APK.
val sonyImageFixtures = providers.gradleProperty("sonyImageFixtures").map { rootProject.file(it) }
val sonyImageFixtureSources = layout.buildDirectory.dir("generated/sonyImageFixtures/kotlin")
val generateSonyImageFixtures = tasks.register("generateSonyImageFixtures") {
    inputs.dir(sonyImageFixtures)
    outputs.dir(sonyImageFixtureSources)
    doLast {
        val directory = sonyImageFixtures.get().canonicalFile
        val manifest = JsonSlurper().parse(directory.resolve("manifest.json")) as Map<*, *>
        val fixtures = manifest["fixtures"] as List<*>
        require(fixtures.isNotEmpty()) { "Sony image manifest contains no fixtures" }
        fun literal(value: Any?) = JsonOutput.toJson(value).replace("$", "\\$")
        val entries = fixtures.map { entry ->
            val fixture = entry as Map<*, *>
            val name = fixture["file"] as String
            require(
                File(name).name == name && name !in listOf(
                    ".",
                    ".."
                )
            ) { "Use a plain fixture filename: $name" }
            val file = directory.resolve(name)
            require(file.isFile && file.canonicalFile.parentFile == directory) { "Missing fixture: $name" }
            val digest = MessageDigest.getInstance("SHA-256")
            file.inputStream().use { input ->
                val buffer = ByteArray(65536)
                var count = input.read(buffer)
                while (count != -1) {
                    digest.update(buffer, 0, count)
                    count = input.read(buffer)
                }
            }
            val hash = digest.digest().joinToString("") { "%02x".format(it) }
            require(hash == fixture["sha256"]) { "Fixture checksum changed: $name" }
            val width = (fixture["width"] as Number).toInt()
            val height = (fixture["height"] as Number).toInt()
            val orientation = (fixture["orientation"] as Number).toInt()
            require(width > 0 && height > 0 && orientation in 1..8) { "Invalid dimensions/orientation: $name" }
            val format = fixture["format"] as String
            require(format in listOf("heif", "jpeg")) { "Unsupported fixture format: $format" }
            val metadata = fixture["metadata"] as Map<*, *>
            require(metadata["make"] == "SONY" && !(metadata["model"] as? String).isNullOrBlank()) { "Expected Sony camera metadata: $name" }
            require(metadata.keys.all {
                it in setOf(
                    "make",
                    "model",
                    "lensModel",
                    "dateTimeOriginal",
                    "iso"
                )
            }) { "Unsupported metadata key: $name" }
            val bitDepth = (fixture["bitDepth"] as? Number)?.toInt() ?: 0
            val chroma = (fixture["chroma"] as? Number)?.toInt() ?: 0
            require(
                format != "heif" || (bitDepth in 8..16 && chroma in listOf(
                    420,
                    422,
                    444
                ))
            ) { "HEIF fixtures need bitDepth and chroma: $name" }
            val tags =
                metadata.entries.joinToString { "${literal(it.key)} to ${literal(it.value as String)}" }
            "SonyImageFixture(${literal(name)}, ${literal(format)}, $width, $height, $orientation, mapOf($tags), $bitDepth, $chroma)"
        }.joinToString(",\n        ")
        val output = sonyImageFixtureSources.get()
            .file("com/sasch/cameragps/sharednew/remote/wifi/SonyImageFixtures.kt").asFile
        output.parentFile.mkdirs()
        output.writeText(
            """
            package com.sasch.cameragps.sharednew.remote.wifi
            internal object SonyImageFixtures {
                const val directory = ${literal(directory.path)}
                val all = listOf(
                    $entries
                )
            }
        """.trimIndent()
        )
    }
}

